from django.db import models
from django.contrib.auth import get_user_model

User = get_user_model()


class ConsumptionForecast(models.Model):
    """
    Subsystem 2 (Coach / Forecasting): Multi-step future energy consumption predictions.
    Generated by S2 ConsumptionForecaster consuming S1 monitoring readings.
    """
    TREND_CHOICES = [
        ('INCREASING', 'Increasing'),
        ('STABLE', 'Stable'),
        ('DECREASING', 'Decreasing'),
    ]

    building = models.ForeignKey(
        'monitoring.Building',
        related_name='forecasts',
        on_delete=models.CASCADE
    )
    forecast_date = models.DateField(db_index=True)
    predicted_kwh = models.FloatField(help_text="Expected energy consumption in kWh")
    confidence_lower_kwh = models.FloatField(help_text="Lower illustrative forecast band (not calibrated)")
    confidence_upper_kwh = models.FloatField(help_text="Upper illustrative forecast band (not calibrated)")
    trend = models.CharField(max_length=20, choices=TREND_CHOICES, default='STABLE')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['forecast_date']
        unique_together = ('building', 'forecast_date')

    def __str__(self):
        return f"{self.building.name} on {self.forecast_date}: {self.predicted_kwh:.1f} kWh ({self.trend})"


class AIRecommendation(models.Model):
    """
    Subsystem 2 (Coach): Actionable energy optimization recommendations.
    Generated either via OpenAI LLM (gpt-4o-mini) or rule-based fallback provider.
    """
    CATEGORY_CHOICES = [
        ('PEAK_SHAVING', 'Peak Shaving'),
        ('HVAC_OPTIMIZATION', 'HVAC Optimization'),
        ('LIGHTING', 'Smart Lighting'),
        ('RENEWABLE_SHIFT', 'Renewable Energy Load Shift'),
        ('BEHAVIORAL', 'Behavioral Nudge'),
    ]

    PRIORITY_CHOICES = [
        ('HIGH', 'High Priority'),
        ('MEDIUM', 'Medium Priority'),
        ('LOW', 'Low Priority'),
    ]

    STATUS_CHOICES = [
        ('PENDING', 'Pending Review'),
        ('ACCEPTED', 'Accepted'),
        ('REJECTED', 'Rejected'),
        ('APPLIED', 'Applied'),
    ]

    building = models.ForeignKey(
        'monitoring.Building',
        related_name='recommendations',
        on_delete=models.CASCADE
    )
    title = models.CharField(max_length=150)
    category = models.CharField(max_length=40, choices=CATEGORY_CHOICES, default='PEAK_SHAVING')
    priority = models.CharField(max_length=20, choices=PRIORITY_CHOICES, default='MEDIUM')
    suggested_action = models.TextField(help_text="Concrete instructions or setpoints to implement")
    estimated_savings_kwh = models.FloatField(default=0.0, help_text="Estimated energy saved in kWh")
    estimated_savings_eur = models.FloatField(null=True, blank=True, default=None, help_text="Unavailable without a priced action scenario")
    confidence_score = models.FloatField(default=0.85, help_text="Model confidence score between 0.0 and 1.0")
    source = models.CharField(
        max_length=30,
        default='OPENAI',
        help_text="Source engine: OPENAI or RULE_BASED fallback"
    )
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='PENDING')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at', '-priority']

    def __str__(self):
        return f"[{self.priority}] {self.title} ({self.building.name})"


class LLMRequestLog(models.Model):
    """
    Subsystem 2 (Coach): Telemetry audit log for LLM invocations and token usage.
    """
    model_name = models.CharField(max_length=60, default='gpt-4o-mini')
    prompt_tokens = models.IntegerField(default=0)
    completion_tokens = models.IntegerField(default=0)
    total_tokens = models.IntegerField(default=0)
    latency_ms = models.IntegerField(default=0)
    status = models.CharField(max_length=30, default='SUCCESS')
    error_message = models.TextField(blank=True, default='')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.status}] {self.model_name} - {self.total_tokens} tokens ({self.latency_ms}ms) @ {self.created_at}"


class RecommendationFeedback(models.Model):
    """
    Subsystem 2 (Coach): User feedback loop for AI recommendations.
    """
    recommendation = models.ForeignKey(
        AIRecommendation,
        related_name='feedback',
        on_delete=models.CASCADE
    )
    user = models.ForeignKey(User, null=True, blank=True, on_delete=models.SET_NULL)
    rating = models.IntegerField(default=5, help_text="Rating from 1 (poor) to 5 (excellent)")
    is_accepted = models.BooleanField(default=True)
    comment = models.TextField(blank=True, default='')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"Feedback for #{self.recommendation.id}: {self.rating} stars"
